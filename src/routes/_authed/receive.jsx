import { useMemo, useState } from "react";
import { createFileRoute } from "@tanstack/react-router";
import { Copy, Check, QrCode as QrIcon, Search } from "lucide-react";
import PageHeader from "@/components/wallet/PageHeader";
import CoinAvatar from "@/components/wallet/CoinAvatar";
import QrCode from "@/components/wallet/QrCode";
import NoticeBanner from "@/components/wallet/NoticeBanner";
import { coins, networkOf } from "@/lib/coin-catalog";

export const Route = createFileRoute("/_authed/receive")({
  head: () => ({
    meta: [
      { title: "Receive — Helix" },
      { name: "description", content: "Share your address or QR code to receive crypto safely." },
    ],
  }),
  component: Receive,
});

function Receive() {
  const [coinId, setCoinId] = useState("btc");
  const [query, setQuery] = useState("");
  const [copied, setCopied] = useState(false);

  const coin = coins.find((item) => item.id === coinId) || coins[0];
  const network = networkOf(coin);
  const address = "";

  const matches = useMemo(() => {
    const term = query.trim().toLowerCase();
    if (!term) return coins;
    return coins.filter(
      (item) =>
        item.symbol.toLowerCase().includes(term) ||
        item.name.toLowerCase().includes(term) ||
        networkOf(item).name.toLowerCase().includes(term),
    );
  }, [query]);

  async function copy() {
    if (!address) return;
    await navigator.clipboard.writeText(address);
    setCopied(true);
    setTimeout(() => setCopied(false), 1600);
  }

  return (
    <>
      <PageHeader
        eyebrow="Deposit"
        title="Receive"
        description="Pick any supported coin. Only send the matching asset on the matching network to this address."
      />

      <NoticeBanner title="Addresses are generated by the signing engine">
        Your keys are created and encrypted on this device. Chain addresses appear here once the signing
        engine is connected, so nothing can be sent to this wallet yet.
      </NoticeBanner>

      <div className="grid gap-4 lg:grid-cols-[320px_minmax(0,1fr)]">
        <section className="panel p-4">
          <div className="relative">
            <Search className="absolute left-3 top-1/2 h-3.5 w-3.5 -translate-y-1/2 text-muted-foreground" />
            <input
              value={query}
              onChange={(event) => setQuery(event.target.value)}
              placeholder="Search coin or network"
              className="w-full rounded-xl border border-border/70 bg-secondary/30 py-2 pl-9 pr-3 text-[13px] outline-none transition-colors placeholder:text-muted-foreground focus:border-primary/50"
            />
          </div>
          <div className="mt-3 max-h-[420px] overflow-y-auto pr-1">
            <div className="grid gap-1.5">
              {matches.map((item) => (
                <button
                  key={item.id}
                  type="button"
                  onClick={() => setCoinId(item.id)}
                  className={`flex items-center gap-3 rounded-xl border px-3 py-2 text-left transition-colors ${
                    coin.id === item.id
                      ? "border-primary/40 bg-primary/10"
                      : "border-border/70 bg-secondary/20 hover:border-border"
                  }`}
                >
                  <CoinAvatar symbol={item.symbol} color={item.color} logo={item.logo} size="sm" />
                  <div className="min-w-0 flex-1">
                    <p className="truncate text-[12px] font-medium">{item.name}</p>
                    <p className="truncate text-[10px] text-muted-foreground">
                      {item.symbol} · {networkOf(item).name}
                    </p>
                  </div>
                </button>
              ))}
            </div>
            {matches.length === 0 && (
              <p className="py-8 text-center text-[12px] text-muted-foreground">Nothing matches that search.</p>
            )}
          </div>
        </section>

        <section className="panel flex flex-col items-center justify-center p-8 text-center">
          <CoinAvatar symbol={coin.symbol} color={coin.color} logo={coin.logo} size="lg" />
          <h2 className="mt-4 font-heading text-base font-semibold tracking-tight">
            {coin.symbol} address not generated yet
          </h2>
          <p className="mt-1.5 max-w-sm text-[12px] leading-relaxed text-muted-foreground">
            This wallet has no {network.name} address yet. Your QR code and address will appear here as
            soon as the {network.name} network is connected.
          </p>

          {address ? (
            <>
              <div className="mt-5">
                <QrCode value={address} />
              </div>
              <button
                type="button"
                onClick={copy}
                className="mt-4 inline-flex items-center gap-2 rounded-xl border border-border/70 bg-secondary/30 px-3 py-2 font-mono text-[12px] transition-colors hover:border-primary/40"
              >
                {copied ? <Check className="h-3.5 w-3.5 text-primary" /> : <Copy className="h-3.5 w-3.5" />}
                {address}
              </button>
            </>
          ) : (
            <span className="mt-5 grid h-12 w-12 place-items-center rounded-2xl bg-secondary text-muted-foreground">
              <QrIcon className="h-5 w-5" />
            </span>
          )}
        </section>
      </div>
    </>
  );
}